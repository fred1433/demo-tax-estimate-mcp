// Bundles the MCP Apps card into one HTML string (app/src/card.generated.js) and copies the
// shared card component to the demo page (page/site/card-core.js).
import { build } from 'esbuild';
import { writeFileSync, copyFileSync, mkdirSync } from 'node:fs';

const out = await build({ entryPoints: ['card/mcp-entry.js'], bundle: true, minify: true, format: 'iife', write: false, target: 'es2022', legalComments: 'none' });
const js = out.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
const html = `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<link rel="preconnect" href="https://fonts.googleapis.com"><link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link href="https://fonts.googleapis.com/css2?family=Public+Sans:wght@400;600;700;800&display=swap" rel="stylesheet">
<style>html,body{margin:0;background:transparent}body{padding:2px}</style></head>
<body><div id="root"><p style="font:14px system-ui;color:#5a6a77;margin:8px">Loading the estimate…</p></div><script>${js}</script></body></html>`;
writeFileSync('app/src/card.generated.js', `// Generated by scripts/build-card.mjs. Do not edit.\nexport default ${JSON.stringify(html)};\n`);
mkdirSync('page/site', { recursive: true });
copyFileSync('card/card-core.js', 'page/site/card-core.js');
console.log(`card html ${(html.length / 1024).toFixed(1)} KB`);
